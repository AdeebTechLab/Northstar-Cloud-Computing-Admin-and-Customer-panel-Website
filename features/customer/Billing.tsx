import { useEffect, useState } from "react";
import { ArrowUpRight, CreditCard, Download, Plus, Printer, Settings } from "lucide-react";
import type { Invoice, PaymentMethod } from "@/types";
import { api, ApiError } from "@/lib/api";
import { useApi } from "@/hooks/useApi";
import { cn } from "@/lib/cn";
import { longDate, money, pad2, shortDate } from "@/lib/format";
import { Card, CardHeader } from "@/components/ui/Card";
import { Button } from "@/components/ui/Button";
import { Badge, StatusBadge } from "@/components/ui/Badge";
import { Field, Input, Select } from "@/components/ui/Field";
import { ConfirmModal, Modal } from "@/components/ui/Modal";
import { Menu } from "@/components/ui/Menu";
import { RowsSkeleton, Skeleton, StatSkeleton } from "@/components/ui/Skeleton";
import { EmptyState, FormAlert } from "@/components/ui/States";
import { Table, Td, Th, THead, Tr } from "@/components/ui/Table";
import { Pagination, usePaged } from "@/components/ui/Pagination";
import { StatCard } from "@/components/ui/StatCard";
import { useToast } from "@/components/ui/Toast";
import { PageHeader } from "@/components/panel/PageHeader";

function printInvoice() {
  document.body.setAttribute("data-printing-modal", "");
  const done = () => {
    document.body.removeAttribute("data-printing-modal");
    window.removeEventListener("afterprint", done);
  };
  window.addEventListener("afterprint", done);
  window.print();
  window.setTimeout(done, 1500);
}

function downloadInvoice(inv: Invoice, account: string) {
  const lines = [
    `Northstar Cloud — Invoice ${inv.id}`,
    `Billing period: ${inv.period}`,
    `Issued: ${longDate(inv.issuedAt)}`,
    `Bill to: ${account}`,
    "",
    ...inv.lines.map((l) => `${l.label.padEnd(30, " ")} ${money(l.amount)}`),
    "".padEnd(40, "-"),
    `${"Total".padEnd(30, " ")} ${money(inv.amount)}`,
    `Status: ${inv.status.toUpperCase()}`,
    "",
    "Demo invoice generated by the Northcloud frontend.",
  ];
  const blob = new Blob([lines.join("\n")], { type: "text/plain" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = `${inv.id}.txt`;
  a.click();
  URL.revokeObjectURL(a.href);
}

export function Billing() {
  const toast = useToast();
  const summary = useApi(() => api.customer.billingSummary(), []);
  const invoices = useApi(() => api.customer.invoices(), []);
  const methods = useApi(() => api.customer.paymentMethods(), []);
  const profile = useApi(() => api.customer.billingProfile(), []);
  const [tab, setTab] = useState<"all" | "paid" | "pending">("all");
  const [page, setPage] = useState(1);
  const [viewing, setViewing] = useState<Invoice | null>(null);

  const [fundsOpen, setFundsOpen] = useState(false);
  const [amount, setAmount] = useState("50");
  const [fundsErr, setFundsErr] = useState("");
  const [fundsState, setFundsState] = useState<"idle" | "sending" | "pending">("idle");
  const [fundsMsg, setFundsMsg] = useState("");

  const [methodOpen, setMethodOpen] = useState(false);
  const [holder, setHolder] = useState("");
  const [brand, setBrand] = useState("Visa");
  const [methodErr, setMethodErr] = useState("");
  const [methodState, setMethodState] = useState<"idle" | "sending" | "pending">("idle");
  const [removeMethod, setRemoveMethod] = useState<PaymentMethod | null>(null);

  const [profileOpen, setProfileOpen] = useState(false);
  const [profileForm, setProfileForm] = useState({ accountName: "", billingEmail: "", country: "", currency: "" });
  const [profileErr, setProfileErr] = useState("");
  const [profileSaving, setProfileSaving] = useState(false);

  useEffect(() => setPage(1), [tab]);

  const list = (invoices.data ?? []).filter((i) => tab === "all" || i.status === tab);
  const paged = usePaged(list, page, 4);

  const submitFunds = async () => {
    const v = Number(amount);
    if (!Number.isFinite(v) || v <= 0) {
      setFundsErr("Enter an amount in USD, e.g. 50.");
      return;
    }
    setFundsErr("");
    setFundsState("sending");
    try {
      const res = await api.customer.addFunds(v);
      setFundsState("pending");
      setFundsMsg(res.message);
    } catch (err) {
      setFundsState("idle");
      setFundsErr(err instanceof ApiError ? err.message : "Payment could not be started.");
    }
  };

  const submitMethod = async () => {
    if (holder.trim().length < 3) {
      setMethodErr("Enter the name shown on the card.");
      return;
    }
    setMethodErr("");
    setMethodState("sending");
    const res = await api.customer.addPaymentMethod({ holderName: holder.trim(), label: brand });
    setMethodState("pending");
    toast({ tone: "pending", title: "Verifying card", message: res.message });
  };

  return (
    <div>
      <PageHeader crumbs={[{ label: "Workspace" }, { label: "Account" }, { label: "Billing & Payments" }]} title="Billing & Payments" subtitle="Manage your account balance, invoices, and payment methods." actions={<Button variant="secondary" icon={<Settings />} onClick={() => { if (profile.data) setProfileForm(profile.data); setProfileErr(""); setProfileOpen(true); }}>Billing Settings</Button>} />

      <div className="relative overflow-hidden rounded-xl bg-gradient-to-r from-navy-800 via-[#173270] to-brand-700 p-6 text-white shadow-card">
        <div className="pointer-events-none absolute -right-10 -top-16 size-56 rounded-full bg-white/10 blur-2xl" aria-hidden="true" />
        <div className="relative flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between">
          <div>
            <p className="text-xs text-slate-300">Available Account Balance</p>
            {summary.loading ? <Skeleton className="mt-2 h-9 w-36 opacity-30" /> : <p className="mt-1 text-[32px] font-bold tracking-tight">{money(summary.data?.balance ?? 0)}</p>}
            <p className="text-xs text-slate-300">Your balance is available for future service charges.</p>
          </div>
          <div className="no-print flex gap-2">
            <Button variant="white" icon={<Plus />} onClick={() => { setAmount("50"); setFundsErr(""); setFundsState("idle"); setFundsOpen(true); }}>Add Funds</Button>
            <Button className="bg-brand-500 hover:bg-brand-400" onClick={() => document.getElementById("invoices")?.scrollIntoView({ behavior: "smooth" })}>View Transactions</Button>
          </div>
        </div>
      </div>

      <div className="mt-4 grid gap-4 sm:grid-cols-3">
        {summary.loading ? <StatSkeleton count={3} /> : (
          <>
            <StatCard label="Current Month Spend" value={money(summary.data!.currentMonthSpend)} sub={`↓ ${Math.abs(summary.data!.spendChangePct)}% compared with last month`} subTone="success" />
            <StatCard label="Next Estimated Invoice" value={money(summary.data!.nextInvoiceEstimate)} sub={`Estimated billing on ${shortDate(summary.data!.nextInvoiceDate)}`} />
            <StatCard label="Outstanding Invoices" value={pad2(invoices.data?.filter((i) => i.status === "pending").length ?? summary.data!.outstandingInvoices)} sub={<span className="flex items-center gap-1.5"><span className="size-1.5 rounded-full bg-amber-500" /> {invoices.data?.some((i) => i.status === "pending") ? "One invoice needs attention" : "All invoices paid"}</span>} />
          </>
        )}
      </div>

      <Card className="mt-4 scroll-mt-24" id="invoices">
        <CardHeader title="Invoices & Billing History" subtitle="Review and download your previous invoices." action={
          <Menu label="Export invoices" trigger={({ toggle }) => <Button variant="secondary" size="sm" iconRight={<Download />} onClick={toggle}>All Invoices</Button>} items={[
            { label: "Download all as text", icon: <Download />, onSelect: () => (invoices.data ?? []).forEach((i) => downloadInvoice(i, profile.data?.accountName ?? "")) },
            { label: "Print this page", icon: <Printer />, onSelect: () => window.print() },
          ]} />
        } />
        <div role="tablist" aria-label="Invoice filter" className="mt-3 flex gap-5 border-b border-line px-5 text-[13px]">
          {(["all", "paid", "pending"] as const).map((t) => (
            <button key={t} type="button" role="tab" aria-selected={tab === t} onClick={() => setTab(t)} className={cn("-mb-px border-b-2 pb-2.5 pt-1 font-medium transition-colors", tab === t ? "border-brand-600 text-brand-600" : "border-transparent text-slate-500 hover:text-slate-800")}>
              {t === "all" ? "All Invoices" : t === "paid" ? "Paid" : "Pending"}
            </button>
          ))}
        </div>
        {invoices.loading ? <RowsSkeleton rows={4} cols={6} /> : list.length === 0 ? <EmptyState title="No invoices here" message="Invoices with this status will appear here." /> : (
          <>
            <Table label="Invoices" minWidth={760}>
              <THead>
                <Th>Invoice</Th><Th>Billing period</Th><Th>Issue date</Th><Th>Amount</Th><Th>Status</Th><Th>Action</Th>
              </THead>
              <tbody>
                {paged.slice.map((i) => (
                  <Tr key={i.id}>
                    <Td className="font-semibold text-slate-900">{i.id}</Td>
                    <Td>{i.period}</Td>
                    <Td>{shortDate(i.issuedAt)}</Td>
                    <Td className="font-semibold text-slate-900">{money(i.amount)}</Td>
                    <Td><StatusBadge status={i.status} /></Td>
                    <Td>
                      {i.status === "pending" ? (
                        <button type="button" onClick={() => setViewing(i)} className="inline-flex items-center gap-1 text-[13px] font-semibold text-brand-600 hover:underline">View Invoice <ArrowUpRight className="size-3.5" /></button>
                      ) : (
                        <span className="flex items-center gap-3">
                          <button type="button" onClick={() => downloadInvoice(i, profile.data?.accountName ?? "")} className="inline-flex items-center gap-1 text-[13px] font-semibold text-brand-600 hover:underline">Download <Download className="size-3.5" /></button>
                          <button type="button" onClick={() => setViewing(i)} className="text-[13px] font-medium text-slate-500 hover:text-slate-800">View</button>
                        </span>
                      )}
                    </Td>
                  </Tr>
                ))}
              </tbody>
            </Table>
            <Pagination variant="text" page={paged.page} pages={paged.pages} onChange={setPage} summary={`Showing ${paged.to - paged.from + 1} of ${paged.total} invoices`} />
          </>
        )}
      </Card>

      <Card className="mt-4">
        <CardHeader title="Payment Methods" subtitle="Manage the payment methods saved to your account." action={<Button variant="secondary" size="sm" icon={<Plus />} onClick={() => { setHolder(""); setMethodErr(""); setMethodState("idle"); setMethodOpen(true); }}>Add Method</Button>} />
        <div className="grid gap-3 p-5 md:grid-cols-2">
          {methods.loading ? [0, 1].map((i) => <Skeleton key={i} className="h-20" />) : (
            <>
              {methods.data?.map((m) => (
                <div key={m.id} className="flex items-center gap-4 rounded-xl border border-line p-4 transition-shadow hover:shadow-card">
                  <span className={cn("grid h-9 w-12 shrink-0 place-items-center rounded-md border text-[11px] font-black", m.brand === "VISA" ? "border-brand-100 bg-brand-50 text-brand-800" : "border-amber-100 bg-amber-50 text-amber-700")}>{m.brand}</span>
                  <div className="min-w-0 flex-1">
                    <p className="text-[13px] font-semibold text-slate-900">{m.label} ending in {m.last4}</p>
                    <p className="text-xs text-slate-500">Expires {m.expires}</p>
                  </div>
                  <div className="flex flex-col items-end gap-1">
                    {m.isDefault ? <Badge tone="brand" className="uppercase">Default</Badge> : null}
                    <Menu label={`Manage ${m.label}`} trigger={({ toggle }) => <button type="button" onClick={toggle} className="text-xs font-semibold text-brand-600 hover:underline">Manage</button>} items={[
                      { label: "Set as default", disabled: m.isDefault, onSelect: async () => { await api.customer.setDefaultPaymentMethod(m.id); toast({ tone: "success", title: "Default payment method updated" }); } },
                      { label: "Remove", danger: true, onSelect: () => setRemoveMethod(m) },
                    ]} />
                  </div>
                </div>
              ))}
              <button type="button" onClick={() => { setHolder(""); setMethodErr(""); setMethodState("idle"); setMethodOpen(true); }} className="flex min-h-20 items-center justify-center gap-2 rounded-xl border border-dashed border-brand-200 bg-brand-50/30 text-[13px] font-semibold text-brand-600 transition-colors hover:border-brand-400 hover:bg-brand-50 md:col-span-1">
                <Plus className="size-4" /> Add a new payment method
              </button>
            </>
          )}
        </div>
      </Card>

      <Card className="mt-4">
        <CardHeader title="Billing Information" subtitle="Account details used for your invoices." action={<Button variant="secondary" size="sm" onClick={() => { if (profile.data) setProfileForm(profile.data); setProfileErr(""); setProfileOpen(true); }}>Edit Details</Button>} />
        <dl className="grid gap-4 p-5 text-[13px] sm:grid-cols-2 lg:grid-cols-4">
          {profile.loading ? [0, 1, 2, 3].map((i) => <Skeleton key={i} className="h-10" />) : [
            ["Account Name", profile.data?.accountName],
            ["Billing Email", profile.data?.billingEmail],
            ["Billing Country", profile.data?.country],
            ["Currency", profile.data?.currency],
          ].map(([k, v]) => (
            <div key={k}>
              <dt className="text-xs text-slate-500">{k}</dt>
              <dd className="mt-1 font-semibold text-slate-900">{v}</dd>
            </div>
          ))}
        </dl>
      </Card>
      <p className="mt-6 text-center text-xs text-slate-400">Northstar Cloud · Billing &amp; Payments</p>

      {/* Invoice viewer (printable) */}
      <Modal open={!!viewing} onClose={() => setViewing(null)} title={`Invoice ${viewing?.id ?? ""}`} description={viewing ? `${viewing.period} · issued ${longDate(viewing.issuedAt)}` : undefined} size="md"
        footer={<>
          <Button variant="secondary" icon={<Printer />} onClick={printInvoice}>Print</Button>
          <Button variant="secondary" icon={<Download />} onClick={() => viewing && downloadInvoice(viewing, profile.data?.accountName ?? "")}>Download</Button>
          {viewing?.status === "pending" ? <Button icon={<CreditCard />} onClick={() => { setViewing(null); setAmount(String(viewing.amount)); setFundsErr(""); setFundsState("idle"); setFundsOpen(true); }}>Pay now</Button> : null}
        </>}>
        {viewing ? (
          <div className="text-[13px]">
            <div className="flex items-start justify-between">
              <div>
                <p className="text-base font-bold text-slate-900">Northstar Cloud</p>
                <p className="text-slate-500">billing@northstar.cloud</p>
              </div>
              <StatusBadge status={viewing.status} />
            </div>
            <div className="mt-5 rounded-lg bg-slate-50 p-3">
              <p className="text-xs text-slate-500">Bill to</p>
              <p className="font-semibold text-slate-900">{profile.data?.accountName}</p>
              <p className="text-slate-500">{profile.data?.billingEmail} · {profile.data?.country}</p>
            </div>
            <table className="mt-5 w-full">
              <thead><tr className="border-b border-line text-left text-xs text-slate-500"><th className="pb-2 font-medium">Description</th><th className="pb-2 text-right font-medium">Amount</th></tr></thead>
              <tbody>
                {viewing.lines.map((l) => <tr key={l.label} className="border-b border-line"><td className="py-2.5 text-slate-700">{l.label}</td><td className="py-2.5 text-right text-slate-900">{money(l.amount)}</td></tr>)}
              </tbody>
              <tfoot><tr><td className="pt-3 font-semibold text-slate-900">Total</td><td className="pt-3 text-right text-base font-bold text-slate-900">{money(viewing.amount)}</td></tr></tfoot>
            </table>
            <p className="mt-5 text-xs text-slate-400">Demo invoice — the authoritative invoice is generated by the billing backend.</p>
          </div>
        ) : null}
      </Modal>

      {/* Add funds */}
      <Modal open={fundsOpen} onClose={() => setFundsOpen(false)} title="Add funds" description="Top up your balance for future service charges." size="sm"
        footer={fundsState === "pending" ? <Button onClick={() => setFundsOpen(false)}>Done</Button> : <>
          <Button variant="secondary" onClick={() => setFundsOpen(false)}>Cancel</Button>
          <Button onClick={submitFunds} loading={fundsState === "sending"} loadingText="Submitting…">Add {Number(amount) > 0 ? money(Number(amount)) : "funds"}</Button>
        </>}>
        {fundsState === "pending" ? <FormAlert tone="pending" title="Payment pending confirmation">{fundsMsg}</FormAlert> : (
          <div className="space-y-4">
            <div className="grid grid-cols-4 gap-2">
              {["25", "50", "100", "250"].map((v) => (
                <button key={v} type="button" onClick={() => setAmount(v)} className={cn("rounded-lg border py-2 text-[13px] font-semibold transition-colors", amount === v ? "border-brand-500 bg-brand-50 text-brand-700" : "border-line hover:bg-slate-50")}>${v}</button>
              ))}
            </div>
            <Field label="Amount (USD)" htmlFor="funds-amount" error={fundsErr}>
              <Input id="funds-amount" inputMode="decimal" value={amount} invalid={!!fundsErr} onChange={(e) => setAmount(e.target.value.replace(/[^\d.]/g, ""))} leading={<span className="text-sm">$</span>} />
            </Field>
            <p className="text-xs text-slate-500">Charged to your default method: {methods.data?.find((m) => m.isDefault)?.label} ending in {methods.data?.find((m) => m.isDefault)?.last4}.</p>
          </div>
        )}
      </Modal>

      {/* Add payment method */}
      <Modal open={methodOpen} onClose={() => setMethodOpen(false)} title="Add a payment method" size="sm"
        footer={methodState === "pending" ? <Button onClick={() => setMethodOpen(false)}>Done</Button> : <>
          <Button variant="secondary" onClick={() => setMethodOpen(false)}>Cancel</Button>
          <Button onClick={submitMethod} loading={methodState === "sending"} loadingText="Connecting…">Continue</Button>
        </>}>
        {methodState === "pending" ? <FormAlert tone="pending" title="Waiting for the payment provider">The card is added once the provider verifies it. This usually takes a few seconds.</FormAlert> : (
          <div className="space-y-4">
            <Field label="Card type" htmlFor="pm-brand">
              <Select id="pm-brand" value={brand} onChange={(e) => setBrand(e.target.value)}><option>Visa</option><option>Mastercard</option></Select>
            </Field>
            <Field label="Name on card" htmlFor="pm-holder" error={methodErr}>
              <Input id="pm-holder" value={holder} invalid={!!methodErr} onChange={(e) => setHolder(e.target.value)} placeholder="e.g. John Doe" autoComplete="cc-name" />
            </Field>
            <div className="rounded-lg border border-dashed border-line bg-slate-50 p-3 text-xs text-slate-500">
              Card number, expiry and CVC are entered in the payment provider&apos;s secure form, which connects here with the NestJS billing API. This demo never handles card numbers.
            </div>
          </div>
        )}
      </Modal>

      {/* Billing profile */}
      <Modal open={profileOpen} onClose={() => setProfileOpen(false)} title="Billing information" size="md"
        footer={<>
          <Button variant="secondary" onClick={() => setProfileOpen(false)}>Cancel</Button>
          <Button loading={profileSaving} loadingText="Saving…" onClick={async () => {
            if (!/^\S+@\S+\.\S+$/.test(profileForm.billingEmail)) { setProfileErr("Enter a valid billing email."); return; }
            setProfileSaving(true);
            await api.customer.updateBillingProfile(profileForm);
            setProfileSaving(false);
            setProfileOpen(false);
            toast({ tone: "success", title: "Billing details saved" });
          }}>Save details</Button>
        </>}>
        <div className="grid gap-4 sm:grid-cols-2">
          <Field label="Account name" htmlFor="bp-name"><Input id="bp-name" value={profileForm.accountName} onChange={(e) => setProfileForm({ ...profileForm, accountName: e.target.value })} /></Field>
          <Field label="Billing email" htmlFor="bp-email" error={profileErr}><Input id="bp-email" type="email" value={profileForm.billingEmail} invalid={!!profileErr} onChange={(e) => setProfileForm({ ...profileForm, billingEmail: e.target.value })} /></Field>
          <Field label="Billing country" htmlFor="bp-country"><Select id="bp-country" value={profileForm.country} onChange={(e) => setProfileForm({ ...profileForm, country: e.target.value })}>{["United States", "Pakistan", "United Kingdom", "Germany", "United Arab Emirates", "Singapore"].map((c) => <option key={c}>{c}</option>)}</Select></Field>
          <Field label="Currency" htmlFor="bp-cur"><Select id="bp-cur" value={profileForm.currency} onChange={(e) => setProfileForm({ ...profileForm, currency: e.target.value })}>{["USD — US Dollar", "EUR — Euro", "GBP — British Pound", "PKR — Pakistani Rupee"].map((c) => <option key={c}>{c}</option>)}</Select></Field>
        </div>
      </Modal>

      <ConfirmModal open={!!removeMethod} onClose={() => setRemoveMethod(null)} title={`Remove ${removeMethod?.label} ending in ${removeMethod?.last4}?`} confirmLabel="Remove card"
        message="Future charges will use your default payment method."
        onConfirm={async () => {
          if (!removeMethod) return;
          try {
            await api.customer.removePaymentMethod(removeMethod.id);
            toast({ tone: "success", title: "Payment method removed" });
          } catch (err) {
            toast({ tone: "error", title: "Not removed", message: err instanceof ApiError ? err.message : "Please try again." });
          }
          setRemoveMethod(null);
        }} />

      {/* Print header for the page */}
      <div className="print-only mt-6 text-xs text-slate-500">Printed from Northstar Cloud · {new Date().toLocaleString()}</div>
    </div>
  );
}
